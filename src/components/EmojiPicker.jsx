export default function EmojiPicker({ onSelect, onClose }) {
  const [search, setSearch] = useState('')
  const [activeCategory, setActiveCategory] = useState('smileys')
  const panelRef = useRef(null)

  useEffect(() => {
    const handleClick = (e) => {
      if (panelRef.current && !panelRef.current.contains(e.target)) onClose?.()
    }
    document.addEventListener('mousedown', handleClick)
    return () => document.removeEventListener('mousedown', handleClick)
  }, [onClose])

  const filtered = search
    ? EMOJI_CATEGORIES.flatMap(c => c.emojis).filter(e => e.includes(search))
    : EMOJI_CATEGORIES.find(c => c.id === activeCategory)?.emojis || []

  return (
    <div className="emoji-picker" ref={panelRef}>
      <div className="emoji-picker-header">
        <div className="emoji-categories">
          {EMOJI_CATEGORIES.map(c => (
            <button
              key={c.id}
              className={`emoji-cat-btn ${activeCategory === c.id ? 'active' : ''}`}
              onClick={() => { setActiveCategory(c.id); setSearch('') }}
            >
              {c.label}
            </button>
          ))}
        </div>
      </div>
      <div className="emoji-grid">
        {filtered.map((e, i) => (
          <button key={i} className="emoji-item" onClick={() => onSelect(e)}>
            {e}
          </button>
        ))}
      </div>
    </div>
  )
}
