export default function EmojiPicker({ onSelect, onClose }) {
  const [activeCategory, setActiveCategory] = useState('smileys')
  const [search, setSearch] = useState('')
  const [showCount, setShowCount] = useState(60)
  const panelRef = useRef(null)
  const gridRef = useRef(null)

  useEffect(() => {
    const handleClick = (e) => {
      if (panelRef.current && !panelRef.current.contains(e.target)) onClose?.()
    }
    document.addEventListener('mousedown', handleClick)
    return () => document.removeEventListener('mousedown', handleClick)
  }, [onClose])

  const currentEmojis = useMemo(() => {
    if (search) {
      const all = EMOJI_CATEGORIES.flatMap(c => c.emojis)
      return all.slice(0, 80)
    }
    return EMOJI_CATEGORIES.find(c => c.id === activeCategory)?.emojis || []
  }, [search, activeCategory])

  const visibleEmojis = currentEmojis.slice(0, showCount)

  const handleScroll = (e) => {
    const el = e.target
    if (el.scrollTop + el.clientHeight >= el.scrollHeight - 40) {
      setShowCount(prev => Math.min(prev + 40, currentEmojis.length))
    }
  }

  useEffect(() => {
    setShowCount(60)
  }, [activeCategory, search])

  return (
    <div className="emoji-picker" ref={panelRef}>
      <div className="emoji-picker-header">
        <div className="emoji-categories">
          {EMOJI_CATEGORIES.map(c => (
            <button
              key={c.id}
              className={`emoji-cat-btn ${activeCategory === c.id && !search ? 'active' : ''}`}
              onClick={() => { setActiveCategory(c.id); setSearch('') }}
            >
              {c.label}
            </button>
          ))}
        </div>
      </div>
      <div className="emoji-grid" ref={gridRef} onScroll={handleScroll}>
        {visibleEmojis.map((e, i) => (
          <button key={`${activeCategory}-${i}`} className="emoji-item" onClick={() => onSelect(e)}>
            <span dangerouslySetInnerHTML={{ __html: emojiToImg(e) }} />
          </button>
        ))}
      </div>
    </div>
  )
}
